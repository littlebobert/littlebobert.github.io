// Generates the QR code for onemorething.tokyo/sign, the in-person guestbook, as square
// 1-bit modules:
//   assets/sign-qr.svg                              for the site
//   workers/portfolio-backend/src/sign-qr.js        inlined in the admin's live page
//
//   swift scripts/generate-sign-qr.swift
//
// The script renders the code back to an image and decodes it, and fails if it doesn't read
// as the URL, so a broken code never gets written.
import AppKit
import CoreImage

let url = "https://onemorething.tokyo/sign"
let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
let quietZone = 4

let filter = CIFilter(name: "CIQRCodeGenerator")!
filter.setValue(url.data(using: .utf8), forKey: "inputMessage")
filter.setValue("M", forKey: "inputCorrectionLevel")
let image = filter.outputImage!
// The generator pads the code with its own one-module margin; read modules from the bitmap.
let context = CIContext()
let cgImage = context.createCGImage(image, from: image.extent)!
let bitmap = NSBitmapImageRep(cgImage: cgImage)
let size = bitmap.pixelsWide
var dark = [[Bool]](repeating: [Bool](repeating: false, count: size), count: size)
for y in 0..<size {
    for x in 0..<size {
        dark[y][x] = (bitmap.colorAt(x: x, y: y)?.brightnessComponent ?? 1) < 0.5
    }
}
// Trim any margin the generator added, then use our own quiet zone.
let rows = dark.indices.filter { dark[$0].contains(true) }
let columns = (0..<size).filter { x in dark.contains { $0[x] } }
let top = rows.first!, left = columns.first!
let modules = rows.last! - top + 1
let total = modules + quietZone * 2

// One path, a run of horizontal module rectangles per row.
var path = ""
for y in 0..<modules {
    var x = 0
    while x < modules {
        guard dark[top + y][left + x] else { x += 1; continue }
        let start = x
        while x < modules && dark[top + y][left + x] { x += 1 }
        path += "M\(start + quietZone) \(y + quietZone)h\(x - start)v1h-\(x - start)z"
    }
}
let svg = """
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \(total) \(total)" shape-rendering="crispEdges" role="img" aria-label="QR code for \(url)"><rect width="\(total)" height="\(total)" fill="#fff"/><path fill="#000" d="\(path)"/></svg>
"""

// Decode a rendering of the SVG's modules before writing anything.
let scale = 12
let check = NSImage(size: NSSize(width: total * scale, height: total * scale), flipped: true) { _ in
    NSColor.white.setFill()
    NSRect(x: 0, y: 0, width: total * scale, height: total * scale).fill()
    NSColor.black.setFill()
    for y in 0..<modules {
        for x in 0..<modules where dark[top + y][left + x] {
            NSRect(x: (x + quietZone) * scale, y: (y + quietZone) * scale, width: scale, height: scale).fill()
        }
    }
    return true
}
let detector = CIDetector(ofType: CIDetectorTypeQRCode, context: nil, options: [CIDetectorAccuracy: CIDetectorAccuracyHigh])!
let checkImage = CIImage(data: check.tiffRepresentation!)!
let decoded = (detector.features(in: checkImage).first as? CIQRCodeFeature)?.messageString
guard decoded == url else {
    FileHandle.standardError.write("QR code decoded as \(decoded ?? "nothing"), not \(url)\n".data(using: .utf8)!)
    exit(1)
}

try! (svg + "\n").write(to: root.appendingPathComponent("assets/sign-qr.svg"), atomically: true, encoding: .utf8)
let module = """
// Generated by scripts/generate-sign-qr.swift: the QR code for \(url).
export const SIGN_URL = '\(url)';
export const SIGN_QR_SVG = '\(svg)';

"""
try! module.write(to: root.appendingPathComponent("workers/portfolio-backend/src/sign-qr.js"), atomically: true, encoding: .utf8)
print("\(modules)×\(modules) modules, decodes as \(decoded!)")
